"""Add or check SPDX license headers.

    spdx-headers.py [--check] [--root DIR] [PATH ...]

Without PATH, walks --root (default: the repository root, one level above tools/).
Adds two lines to each source file that has none:

    SPDX-License-Identifier: AGPL-3.0-only
    SPDX-FileCopyrightText: 2026 Ning Bao

in the file's own comment syntax. Running it twice changes nothing. Files that
already carry an SPDX-License-Identifier are left alone, whatever its value.
--check changes nothing and exits 1 if any file lacks a header.
Generated and vendored third-party files are skipped (see SKIP_DIRS, SKIP_NAMES).
"""
import argparse
import os
import sys

LICENSE = "AGPL-3.0-only"
COPYRIGHT = "2026 Ning Bao"
LINES = [f"SPDX-License-Identifier: {LICENSE}", f"SPDX-FileCopyrightText: {COPYRIGHT}"]

SLASH = ("//", None)
HASH = ("#", None)

BY_EXT = {
    ".rs": SLASH, ".c": SLASH, ".h": SLASH, ".cc": SLASH, ".cpp": SLASH, ".cxx": SLASH,
    ".hpp": SLASH, ".hh": SLASH, ".m": SLASH, ".mm": SLASH, ".swift": SLASH,
    ".qml": SLASH, ".js": SLASH, ".mjs": SLASH,
    ".glsl": SLASH, ".vert": SLASH, ".frag": SLASH, ".comp": SLASH, ".wgsl": SLASH,
    ".py": HASH, ".sh": HASH, ".bash": HASH, ".cmake": HASH, ".toml": HASH,
    ".yml": HASH, ".yaml": HASH,
}
BY_NAME = {"CMakeLists.txt": HASH, "PKGBUILD": HASH}

SKIP_DIRS = {
    ".git", "target", "build", "node_modules", "vendor", "third_party", "third-party",
    "generated", "Generated", ".build", "DerivedData", "licenses", "LICENSES",
}
SKIP_NAMES = {"Cargo.lock", "Package.resolved"}
# Path fragments (posix) that mark generated or vendored output.
SKIP_PARTS = ("sodium-ui/third_party/", "uniffi/generated/")
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Generated by", "This file was automatically generated")


def syntax(path):
    name = os.path.basename(path)
    if name in SKIP_NAMES:
        return None
    if name in BY_NAME:
        return BY_NAME[name]
    return BY_EXT.get(os.path.splitext(name)[1])


def is_text(data):
    return b"\0" not in data[:4096]


def with_header(path, raw):
    """`raw` (the bytes of the file `path`) with the header added: ("ok", raw) when it has one, ("skipped", raw)
    when it is not a source file, else ("added", the new bytes). Also used by sync-sodium-ui.py."""
    rel = path.replace(os.sep, "/")
    if any(p in rel for p in SKIP_PARTS):
        return "skipped", raw
    syn = syntax(path)
    if syn is None or not is_text(raw):
        return "skipped", raw
    text = raw.decode("utf-8", errors="replace")
    head = text[:2048]
    if "SPDX-License-Identifier" in head:
        return "ok", raw
    if any(m in head for m in GENERATED_MARKERS):
        return "skipped", raw
    prefix = syn[0]
    header = "".join(f"{prefix} {l}\n" for l in LINES)
    nl = "\r\n" if "\r\n" in text else "\n"
    if nl != "\n":
        header = header.replace("\n", nl)
    lines = text.split("\n")
    insert_at = 0
    if lines and lines[0].startswith("#!"):
        insert_at = 1
    elif lines and lines[0].startswith("<?xml"):
        insert_at = 1
    out = "\n".join(lines[:insert_at]) + (nl if insert_at else "")
    rest = "\n".join(lines[insert_at:])
    return "added", (out + header + rest).encode("utf-8")


def process(path, write):
    """Return 'ok', 'added', 'skipped' for a file."""
    with open(path, "rb") as f:
        raw = f.read()
    state, new = with_header(path, raw)
    if state == "added" and write:
        with open(path, "wb") as f:
            f.write(new)
    return state


def walk(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for n in sorted(filenames):
            yield os.path.join(dirpath, n)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report files without a header; change nothing")
    ap.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    ap.add_argument("paths", nargs="*")
    a = ap.parse_args()
    files = []
    for p in a.paths or [a.root]:
        if os.path.isdir(p):
            files.extend(walk(p))
        else:
            files.append(p)
    missing = 0
    for f in files:
        r = process(f, write=not a.check)
        if r == "added":
            missing += 1
            print(("missing: " if a.check else "added:   ") + os.path.relpath(f))
    if a.check:
        if missing:
            print(f"{missing} file(s) without an SPDX header", file=sys.stderr)
            return 1
        print("all files have SPDX headers")
    else:
        print(f"{missing} file(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
